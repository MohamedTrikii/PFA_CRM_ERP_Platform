import 'package:flutter/material.dart';
import 'package:flutter_riverpod/flutter_riverpod.dart';

import '../../../core/api/models.dart';
import '../../../core/api/portal_api.dart';
import '../../../core/database/app_database.dart';
import '../data/portal_notifiers.dart';

final purchaseInvoicesProvider = FutureProvider<List<PurchaseInvoiceEntry>>((ref) async {
  try {
    final db = ref.watch(appDatabaseProvider);
    return db.getPurchaseInvoices();
  } catch (_) {
    return [];
  }
});

class PurchaseInvoiceListScreen extends ConsumerWidget {
  const PurchaseInvoiceListScreen({super.key});

  @override
  Widget build(BuildContext context, WidgetRef ref) {
    final invoicesAsync = ref.watch(purchaseInvoicesProvider);

    return Scaffold(
      appBar: AppBar(
        title: const Text('Factures d\'Achat'),
      ),
      floatingActionButton: FloatingActionButton(
        onPressed: () {
          Navigator.of(context).push(
            MaterialPageRoute(builder: (_) => const PurchaseInvoiceFormScreen()),
          );
        },
        child: const Icon(Icons.add),
      ),
      body: invoicesAsync.when(
        loading: () => const Center(child: CircularProgressIndicator()),
        error: (e, _) => Center(child: Text('Erreur: $e')),
        data: (invoices) => invoices.isEmpty
            ? const _EmptyView()
            : ListView.builder(
                padding: const EdgeInsets.all(12),
                itemCount: invoices.length,
                itemBuilder: (_, i) => _InvoiceCard(invoice: invoices[i]),
              ),
      ),
    );
  }
}

class _InvoiceCard extends StatelessWidget {
  final PurchaseInvoiceEntry invoice;

  const _InvoiceCard({required this.invoice});

  @override
  Widget build(BuildContext context) {
    return Card(
      margin: const EdgeInsets.only(bottom: 10),
      child: ListTile(
        leading: Icon(Icons.receipt_long_outlined, color: Colors.teal.shade600),
        title: Text(invoice.invoiceNumber, style: const TextStyle(fontWeight: FontWeight.w600)),
        subtitle: Text(
          '${invoice.invoiceDate.day}/${invoice.invoiceDate.month}/${invoice.invoiceDate.year} • ${invoice.supplierName}',
          style: const TextStyle(fontSize: 12),
        ),
        trailing: Column(
          mainAxisAlignment: MainAxisAlignment.center,
          crossAxisAlignment: CrossAxisAlignment.end,
          children: [
            Text('${invoice.totalTTC.toStringAsFixed(2)} MAD',
                style: const TextStyle(fontWeight: FontWeight.bold)),
            if (!invoice.synced)
              const Text('Hors-ligne', style: TextStyle(fontSize: 10, color: Colors.orange)),
          ],
        ),
      ),
    );
  }
}

// Use the `PurchaseInvoiceEntry` generated by Drift in `app_database.dart`.


class PurchaseInvoiceFormScreen extends ConsumerWidget {
  const PurchaseInvoiceFormScreen({super.key});

  @override
  Widget build(BuildContext context, WidgetRef ref) {
    final formData = ref.watch(purchaseInvoiceFormNotifierProvider);
    final formNotifier = ref.read(purchaseInvoiceFormNotifierProvider.notifier);
    final api = ref.watch(portalApiProvider);
    final db = ref.watch(appDatabaseProvider);

    return Scaffold(
      appBar: AppBar(
        title: const Text('Ajouter Facture d\'Achat'),
      ),
      body: ListView(
        padding: const EdgeInsets.all(16),
        children: [
          _FormSection(
            title: 'Fournisseur *',
            child: TextField(
              decoration: InputDecoration(
                hintText: 'Sélectionner un fournisseur',
                border: OutlineInputBorder(borderRadius: BorderRadius.circular(8)),
                suffixIcon: const Icon(Icons.arrow_drop_down),
              ),
              onChanged: (val) => formNotifier.setSupplier('supplier_id', val),
            ),
          ),
          const SizedBox(height: 16),
          _FormSection(
            title: 'N° Facture *',
            child: TextField(
              decoration: InputDecoration(
                hintText: 'Ex: FAC-2026-001',
                border: OutlineInputBorder(borderRadius: BorderRadius.circular(8)),
              ),
              onChanged: (val) => formNotifier.setInvoiceNumber(val),
            ),
          ),
          const SizedBox(height: 16),
          _FormSection(
            title: 'Date Facture *',
            child: GestureDetector(
              onTap: () async {
                final picked = await showDatePicker(
                  context: context,
                  initialDate: formData.invoiceDate,
                  firstDate: DateTime(2020),
                  lastDate: DateTime.now().add(const Duration(days: 30)),
                );
                if (picked != null) {
                  formNotifier.setInvoiceDate(picked);
                }
              },
              child: Container(
                padding: const EdgeInsets.symmetric(horizontal: 12, vertical: 12),
                decoration: BoxDecoration(
                  border: Border.all(color: Colors.grey),
                  borderRadius: BorderRadius.circular(8),
                ),
                child: Row(
                  mainAxisAlignment: MainAxisAlignment.spaceBetween,
                  children: [
                    Text('${formData.invoiceDate.day}/${formData.invoiceDate.month}/${formData.invoiceDate.year}'),
                    const Icon(Icons.calendar_today, size: 18),
                  ],
                ),
              ),
            ),
          ),
          const SizedBox(height: 16),
          Row(
            children: [
              Expanded(
                flex: 2,
                child: _FormSection(
                  title: 'Montant HT (MAD) *',
                  child: TextField(
                    keyboardType: TextInputType.number,
                    decoration: InputDecoration(
                      hintText: '0.00',
                      border: OutlineInputBorder(borderRadius: BorderRadius.circular(8)),
                    ),
                    onChanged: (val) => formNotifier.setAmount(double.tryParse(val) ?? 0),
                  ),
                ),
              ),
              const SizedBox(width: 12),
              Expanded(
                child: _FormSection(
                  title: 'TVA (%)',
                  child: TextField(
                    keyboardType: TextInputType.number,
                    decoration: InputDecoration(
                      hintText: '20',
                      border: OutlineInputBorder(borderRadius: BorderRadius.circular(8)),
                    ),
                    onChanged: (val) => formNotifier.setTvaRate(double.tryParse(val) ?? 20),
                  ),
                ),
              ),
            ],
          ),
          const SizedBox(height: 16),
          _FormSection(
            title: 'Notes',
            child: TextField(
              maxLines: 3,
              decoration: InputDecoration(
                hintText: 'Commentaires additionnels...',
                border: OutlineInputBorder(borderRadius: BorderRadius.circular(8)),
              ),
              onChanged: (val) => formNotifier.setNotes(val),
            ),
          ),
          const SizedBox(height: 16),
          _FormSection(
            title: 'Pièce Jointe',
            child: _AttachmentPicker(
              filePath: formData.attachmentPath,
              onFileSelected: (path) => formNotifier.setAttachment(path),
            ),
          ),
          const SizedBox(height: 24),
          _SummaryCardInvoice(data: formData),
          const SizedBox(height: 16),
          ElevatedButton(
            onPressed: () => _saveInvoice(context, ref, formNotifier, api, db),
            style: ElevatedButton.styleFrom(
              padding: const EdgeInsets.symmetric(vertical: 16),
            ),
            child: const Text('Sauvegarder Facture'),
          ),
        ],
      ),
    );
  }

  Future<void> _saveInvoice(
    BuildContext context,
    WidgetRef ref,
    PurchaseInvoiceFormNotifier formNotifier,
    PortalApi api,
    AppDatabase db,
  ) async {
    try {
      await formNotifier.save(api, db);
      ref.invalidate(purchaseInvoiceListProvider);
      if (context.mounted) {
        ScaffoldMessenger.of(context).showSnackBar(
          const SnackBar(content: Text('Facture sauvegardée')),
        );
        Navigator.pop(context);
      }
    } catch (e) {
      if (context.mounted) {
        ScaffoldMessenger.of(context).showSnackBar(
          SnackBar(content: Text('Erreur: $e'), backgroundColor: Colors.red),
        );
      }
    }
  }
}

class _FormSection extends StatelessWidget {
  final String title;
  final Widget child;

  const _FormSection({required this.title, required this.child});

  @override
  Widget build(BuildContext context) {
    return Column(
      crossAxisAlignment: CrossAxisAlignment.start,
      children: [
        Text(title, style: Theme.of(context).textTheme.titleSmall?.copyWith(fontWeight: FontWeight.bold)),
        const SizedBox(height: 8),
        child,
      ],
    );
  }
}

class _AttachmentPicker extends StatelessWidget {
  final String? filePath;
  final ValueChanged<String> onFileSelected;

  const _AttachmentPicker({required this.filePath, required this.onFileSelected});

  @override
  Widget build(BuildContext context) {
    return Column(
      children: [
        if (filePath != null)
          Padding(
            padding: const EdgeInsets.only(bottom: 8),
            child: Chip(
              label: Text(filePath!.split('/').last),
              deleteIcon: const Icon(Icons.close),
              onDeleted: () => onFileSelected(''),
            ),
          ),
        Row(
          children: [
            Expanded(
              child: ElevatedButton.icon(
                onPressed: () {
                  // TODO: Integrate file picker (e.g., image_picker or file_picker)
                  ScaffoldMessenger.of(context).showSnackBar(
                    const SnackBar(content: Text('Scan de facture en développement')),
                  );
                },
                icon: const Icon(Icons.photo_camera),
                label: const Text('Scanner'),
              ),
            ),
            const SizedBox(width: 8),
            Expanded(
              child: ElevatedButton.icon(
                onPressed: () {
                  // TODO: Integrate file picker
                  ScaffoldMessenger.of(context).showSnackBar(
                    const SnackBar(content: Text('Joindre fichier en développement')),
                  );
                },
                icon: const Icon(Icons.attach_file),
                label: const Text('Fichier'),
              ),
            ),
          ],
        ),
      ],
    );
  }
}

class _SummaryCardInvoice extends StatelessWidget {
  final PurchaseInvoiceData data;

  const _SummaryCardInvoice({required this.data});

  @override
  Widget build(BuildContext context) {
    final ht = data.amountHT;
    final tva = ht * (data.tvaRate / 100);
    final ttc = ht + tva;

    return Card(
      color: Colors.green.shade50,
      child: Padding(
        padding: const EdgeInsets.all(16),
        child: Column(
          children: [
            Row(
              mainAxisAlignment: MainAxisAlignment.spaceBetween,
              children: [
                const Text('Montant HT'),
                Text('${ht.toStringAsFixed(2)} MAD', style: const TextStyle(fontWeight: FontWeight.bold)),
              ],
            ),
            const SizedBox(height: 8),
            Row(
              mainAxisAlignment: MainAxisAlignment.spaceBetween,
              children: [
                const Text('TVA'),
                Text('${tva.toStringAsFixed(2)} MAD', style: const TextStyle(fontWeight: FontWeight.bold)),
              ],
            ),
            const Divider(height: 16),
            Row(
              mainAxisAlignment: MainAxisAlignment.spaceBetween,
              children: [
                const Text('Total TTC', style: TextStyle(fontWeight: FontWeight.bold, fontSize: 16)),
                Text('${ttc.toStringAsFixed(2)} MAD',
                    style: const TextStyle(fontWeight: FontWeight.bold, fontSize: 16, color: Colors.green)),
              ],
            ),
          ],
        ),
      ),
    );
  }
}

